#!/usr/bin/env bash
# ============================================================
# build/flame.sh — build the Dart/Flame port of Asteroids
# ============================================================
# Pipeline:  framec (.fdart -> app/lib/asteroids.dart)  ->  flutter build web
#            ->  games/asteroids/versions/flame/
#
# Unlike the Godot ports there's no shared-engine trick — a Flutter web app
# bundles its own CanvasKit runtime (~37 MB). It's served self-hosted
# (--no-web-resources-cdn) so the bundle is fully self-contained, and the
# base-href points the loader at the deploy subpath.
#
# Pre-reqs:  framec (FRAMEC), Flutter 3.44.x on PATH (or FLUTTER=), web enabled.
#   - FSM source of truth is asteroids.fdart; app/lib/main.dart is the
#     hand-written Flame host; app/lib/asteroids.dart is regenerated here.
# ============================================================
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SPIKE="$REPO/build/spike-flame"
APP="$SPIKE/app"
OUT="$REPO/games/asteroids/versions/flame"
FRAMEC="${FRAMEC:-framec}"
FLUTTER="${FLUTTER:-flutter}"
BASE="/games/asteroids/versions/flame/"

echo "==> [1/3] framec: asteroids.fdart -> app/lib/asteroids.dart (FSM)"
"$FRAMEC" -l dart "$SPIKE/asteroids.fdart" > "$APP/lib/asteroids.dart"
# framec's dart codegen doesn't emit a suppression header (the rust target emits
# #[allow(...)]); prepend ignore_for_file so the generated FSM scaffolding's
# unused-field / snake_case warnings don't drown out real ones. (framec polish:
# the dart backend should emit this itself — see the roadmap note in README.)
TMP="$(mktemp)"
{
  printf '// GENERATED by framec from asteroids.fdart — do not edit.\n'
  printf '// ignore_for_file: unused_field, unused_element, unused_local_variable, non_constant_identifier_names, constant_identifier_names, library_private_types_in_public_api, prefer_final_fields, type=lint\n\n'
  cat "$APP/lib/asteroids.dart"
} > "$TMP"
mv "$TMP" "$APP/lib/asteroids.dart"

echo "==> [2/3] flutter build web (self-hosted canvaskit, base-href $BASE)"
( cd "$APP" && "$FLUTTER" build web --release --base-href "$BASE" --no-web-resources-cdn )

echo "==> [3/3] publish -> $OUT"
rm -rf "$OUT"; mkdir -p "$OUT"
cp -R "$APP/build/web/." "$OUT/"
echo "==> done ($(du -sh "$OUT" | cut -f1))"
